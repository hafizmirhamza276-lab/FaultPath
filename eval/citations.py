#!/usr/bin/env python3
"""
citations.py
Citations are RENDERED BY CODE, never generated by a model.

The model refers to a fact by id. This module turns that id into a citation by
reading the ground truth. What the model does not type, it cannot get wrong --
which moves citation accuracy from something we measure after the fact to
something that is structurally true before it.

    render(["CA451:6:meas:0"]) -> [Citation]
    resolve(citation, pdf)     -> Resolution

The resolver is the point of the file. It re-opens the source PDF at the cited
page and checks the verbatim text is actually there. A citation that cannot be
resolved back to the source is not a citation, it is a claim about one -- and
the difference is invisible until someone checks.

No LLM. Rendering is a dictionary lookup; resolution is a substring test against
the page's own text layer.
"""
import glob
import json
import os
import re
import unicodedata

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GOLD = os.environ.get("GOLD_DIR", os.path.join(REPO_ROOT, "golden"))
DEFAULT_PDF = os.environ.get(
    "KOMATSU_PDF", os.path.join(os.path.dirname(REPO_ROOT),
                                "komatsu-manuals", "SEN06867-13.pdf"))

FACT_ID_RE = re.compile(r"^(?P<code>[A-Z0-9@#]{4,7}):(?P<step>\d+):"
                        r"(?P<kind>step|meas|branch|header):(?P<index>\d+)$")


class UnknownFact(KeyError):
    """Raised when a fact id does not exist in the ground truth.

    Loud on purpose. A model that invents a fact id must not be able to produce
    a citation-shaped object; that would be the exact failure this design
    exists to prevent, wearing the disguise of a citation.
    """


def _load():
    recs = {}
    for p in sorted(glob.glob(os.path.join(GOLD, "failure_codes", "*.json"))):
        with open(p, encoding="utf-8") as f:
            r = json.load(f)
        recs[r["code"]] = r
    return recs


_RECORDS = None


def records():
    global _RECORDS
    if _RECORDS is None:
        _RECORDS = _load()
    return _RECORDS


def _fact(fact_id):
    """(record, verbatim_text, provenance) for one fact id."""
    m = FACT_ID_RE.match(fact_id or "")
    if not m:
        raise UnknownFact(f"malformed fact id: {fact_id!r}")
    code, step, kind, idx = (m["code"], int(m["step"]), m["kind"], int(m["index"]))
    rec = records().get(code)
    if rec is None:
        raise UnknownFact(f"no such failure code: {code}")

    if kind == "meas" and step == 0:
        ms = rec["standalone_measurements"]
        if idx >= len(ms):
            raise UnknownFact(f"no standalone measurement {idx} on {code}")
        return rec, ms[idx]["criteria"], ms[idx]["provenance"]

    st = next((s for s in rec["steps"] if s["step"] == step), None)
    if st is None:
        raise UnknownFact(f"no step {step} on {code}")

    if kind == "step":
        return rec, st.get("cause") or st.get("procedure") or "", st["provenance"]
    if kind == "meas":
        if idx >= len(st["measurements"]):
            raise UnknownFact(f"no measurement {idx} on {code} step {step}")
        mm = st["measurements"][idx]
        return rec, mm["criteria"], mm["provenance"]
    if kind == "branch":
        names = sorted(st.get("branches") or {})
        if idx >= len(names):
            raise UnknownFact(f"no branch {idx} on {code} step {step}")
        return rec, st["branches"][names[idx]], st["provenance"]
    if kind == "header":
        prov = rec.get("header_provenance") or {}
        fields = ["title", "action_level", "detail_of_failure",
                  "controller_action", "machine_effect", "related_information"]
        if idx >= len(fields):
            raise UnknownFact(f"no header field {idx}")
        return rec, rec.get(fields[idx]) or "", prov
    raise UnknownFact(f"unknown fact kind: {kind}")


def render(fact_ids):
    """Fact ids -> citations. Pure lookup; no text is composed or reworded."""
    out = []
    for fid in fact_ids:
        rec, text, prov = _fact(fid)
        out.append({
            "fact_id": fid,
            "manual_id": rec["manual_id"],
            "revision": rec["revision"],
            "model": rec["model"],
            "section": rec["section"],
            "manual_page": prov.get("manual_page"),
            "pdf_page": prov.get("pdf_page"),
            "verbatim_text": text,
        })
    return out


# ------------------------------------------------------------------ resolver

def _norm(s):
    """Normalise a string the same way the extractor normalised the cell it
    came from, so the two are comparable.

    This must mirror pipeline/extract_golden.py's clean(): newlines become
    spaces and words broken across a line are rejoined. The manual typesets
    'Approx-\\nimately\\n1.7 kOhm', which clean() stores as
    'Approximately 1.7 kOhm'; without the same de-hyphenation here the resolver
    rejects a citation whose text is genuinely on the page. Ohm codepoints are
    folded because the document mixes U+2126 and U+03A9.

    Digits are never touched. A citation to the wrong number must still fail.
    """
    s = unicodedata.normalize("NFC", str(s or ""))
    s = s.replace("\n", " ")
    s = re.sub(r"([a-z])-\s+([a-z])", r"\1\2", s)     # clean()'s de-hyphenation
    for form in ("Ω", "Ω", "ω", "ohms", "ohm"):
        s = re.sub(re.escape(form), " ohm ", s, flags=re.I)
    s = re.sub(r"[\s­]+", " ", s)
    return s.strip().lower()


def _tight(s):
    """_norm with every space and hyphen removed. Digits and letter order are
    untouched, so this cannot make a wrong value look right."""
    return re.sub(r"[\s\-­]+", "", _norm(s))


class PageText:
    """Lazy, cached page-text reader. Opens the PDF once per process."""

    def __init__(self, pdf_path=None):
        self.path = pdf_path or DEFAULT_PDF
        self._doc = None
        self._cache = {}

    def available(self):
        return bool(self.path) and os.path.isfile(self.path)

    def text(self, pdf_page):
        if pdf_page in self._cache:
            return self._cache[pdf_page]
        if self._doc is None:
            import fitz
            self._doc = fitz.open(self.path)
        t = self._doc[pdf_page - 1].get_text()
        self._cache[pdf_page] = t
        return t

    def close(self):
        if self._doc is not None:
            self._doc.close()
            self._doc = None


def resolve(citation, pages=None):
    """Re-read the cited page and confirm the verbatim text is on it.

    Returns {resolved, reason, ...}. `resolved` is None -- not False -- when the
    PDF is unavailable, so an environment without the manual reports "could not
    check" rather than silently reporting "citation is fine".
    """
    pages = pages or PageText()
    out = {"fact_id": citation.get("fact_id"),
           "manual_page": citation.get("manual_page"),
           "pdf_page": citation.get("pdf_page"),
           "resolved": None, "reason": ""}

    if not pages.available():
        out["reason"] = f"source PDF not available at {pages.path}"
        return out
    if not citation.get("pdf_page"):
        out.update(resolved=False, reason="citation carries no pdf_page")
        return out

    try:
        page_text = pages.text(citation["pdf_page"])
    except Exception as exc:
        out.update(resolved=False, reason=f"could not read page: {exc!r}")
        return out

    want = _norm(citation.get("verbatim_text"))
    if not want:
        out.update(resolved=False, reason="citation carries no verbatim_text")
        return out

    if _norm(page_text).find(want) >= 0:
        out.update(resolved=True, reason="verbatim text found on cited page")
        return out

    # Second chance, for extractor disagreement only. golden/ is built with
    # pdfplumber's table extraction; this resolver reads the page with PyMuPDF,
    # and the two place hyphens and spaces differently inside a word broken
    # across a line -- pdfplumber yields 'control ler' where PyMuPDF yields
    # 'control-\nler'. Comparing with spaces and hyphens removed asks "is this
    # text on this page" without asking the two libraries to agree on typography.
    #
    # This does NOT touch digits or letter order, so a wrong value and a wrong
    # page both still fail. The distinct reason string keeps it visible rather
    # than quietly folding it into a clean result.
    if _tight(page_text).find(_tight(citation.get("verbatim_text"))) >= 0:
        out.update(resolved=True,
                   reason="found; whitespace/hyphenation differs between "
                          "pdfplumber and PyMuPDF")
        return out

    out.update(resolved=False,
               reason="verbatim text NOT on the cited page")
    return out


def resolve_all(citations, pages=None):
    pages = pages or PageText()
    return [resolve(c, pages) for c in citations]


if __name__ == "__main__":
    import sys
    ids = sys.argv[1:] or ["CA451:6:meas:0"]
    pages = PageText()
    for c in render(ids):
        r = resolve(c, pages)
        print(json.dumps(c, ensure_ascii=False, indent=2))
        print("  resolved:", r["resolved"], "-", r["reason"])
    pages.close()
